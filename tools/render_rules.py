#!/usr/bin/env python3
"""Validate shared data and deterministically render the public classic list."""
import argparse
import ipaddress
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def shared_rules(data):
    if set(data) != {'schema_version', 'sections', 'sources'} or data['schema_version'] != 1:
        raise ValueError('unsupported shared-rule schema')
    if not isinstance(data['sections'], list) or not data['sections']:
        raise ValueError('empty shared rules')
    result, names, keys = [], set(), set()
    for section in data['sections']:
        if set(section) != {'name', 'policy', 'type', 'domains'}:
            raise ValueError('unexpected section fields')
        name = section['name']
        if not re.fullmatch(r'[a-z][a-z0-9_]{0,63}', name) or name in names:
            raise ValueError('invalid section name')
        names.add(name)
        if section['policy'] not in ('aigc', 'grok') or section['type'] not in ('DOMAIN', 'DOMAIN-SUFFIX'):
            raise ValueError('unsupported policy or match type')
        if not isinstance(section['domains'], list) or not section['domains']:
            raise ValueError('empty section')
        for domain in section['domains']:
            if not isinstance(domain, str) or len(domain) > 253 or domain != domain.lower():
                raise ValueError('invalid domain')
            labels = domain.split('.')
            if len(labels) < 2 or any(not re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', x) for x in labels):
                raise ValueError('invalid domain')
            try:
                ipaddress.ip_address(domain)
            except ValueError:
                pass
            else:
                raise ValueError('IP addresses are not shared domain rules')
            key = (section['type'], domain)
            if key in keys:
                raise ValueError('duplicate shared rule')
            for previous_kind, previous_domain, previous_policy in result:
                if (previous_kind == 'DOMAIN-SUFFIX' and previous_policy != section['policy']
                        and (domain == previous_domain or domain.endswith('.' + previous_domain))):
                    raise ValueError('earlier suffix shadows a different policy')
            keys.add(key)
            result.append((section['type'], domain, section['policy']))
    if len(result) > 1024:
        raise ValueError('too many shared rules')
    if not isinstance(data['sources'], list) or not all(isinstance(x, str) and x.startswith('https://') for x in data['sources']):
        raise ValueError('invalid source references')
    for value in data['sources']:
        source = urlsplit(value)
        if not source.hostname or '@' in source.netloc or source.query:
            raise ValueError('source references must not contain credentials or query parameters')
    return result


def render(data, legacy):
    rules = shared_rules(data)
    lines = legacy.decode('utf-8').splitlines()
    keys = {(kind, domain) for kind, domain, _ in rules}
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith(('#', ';')):
            continue
        parts = line.split(',')
        if len(parts) not in (2, 3) or not parts[1]:
            raise ValueError('invalid legacy rule')
        if parts[0] not in ('DOMAIN', 'DOMAIN-SUFFIX', 'DOMAIN-KEYWORD', 'IP-CIDR', 'IP-CIDR6', 'IP-ASN'):
            raise ValueError('unsupported legacy rule')
        if len(parts) == 3 and parts[2] != 'no-resolve':
            raise ValueError('legacy list must not bind a policy')
        if (parts[0], parts[1]) in keys:
            raise ValueError('shared rule duplicated in legacy input')
    newline = b'\r\n' if b'\r\n' in legacy else b'\n'
    head = ['# Generated by tools/render_rules.py; do not edit AI.list directly.',
            '# Shared rules: rules/aigc-shared.json; legacy public-only rules: rules/AI.legacy.list.',
            '# Policy names are supplied by the consumer.', '# BEGIN SHARED AIGC RULES']
    head += [kind + ',' + domain for kind, domain, _ in rules]
    head += ['# END SHARED AIGC RULES']
    return newline.join(x.encode() for x in head) + newline * 2 + legacy


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    data = json.loads((ROOT / 'rules/aigc-shared.json').read_text())
    output = render(data, (ROOT / 'rules/AI.legacy.list').read_bytes())
    target = ROOT / 'AI.list'
    if args.check:
        if target.read_bytes() != output:
            raise SystemExit('AI.list is stale; run python3 tools/render_rules.py')
    else:
        target.write_bytes(output)
    print('shared rules and AI.list: PASS')


if __name__ == '__main__':
    main()
